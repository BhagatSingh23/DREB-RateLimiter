package com.dreb.ratelimit;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Locale;

import static org.junit.jupiter.api.Assertions.assertTrue;

@DisplayName("Deterministic Trace Test - Worked Example")
public class WorkedExampleTraceTest {

    @Test
    @DisplayName("Generates docs/worked_example.md with step-by-step trace")
    void generateWorkedExample() throws IOException {
        StringBuilder md = new StringBuilder();
        md.append("# DREB v2 Worked Example Trace\n\n");
        md.append("This document is generated by `WorkedExampleTraceTest` as a reproducible, deterministic trace of DREB v2.\n");
        md.append("It illustrates state evolution across:\n");
        md.append("1. **Initial Idle Period**: client rests for 10.0 seconds, allowing idle credit to accrue up to `idleCap`.\n");
        md.append("2. **One Legitimate Burst**: client draws on idle credit to absorb an initial burst.\n");
        md.append("3. **10 Repeated Burst Cycles**: client repeatedly bursts every 1.5 seconds, triggering abuse penalty escalation.\n\n");

        md.append("## Configuration\n");
        md.append("- `burstMax`: 10.0, `burstRate`: 5.0 tokens/s\n");
        md.append("- `sustainedMax`: 30.0, `sustainedRate`: 10.0 tokens/s\n");
        md.append("- `idleGain`: 5.0 credit/s, `idleCap`: 20.0, `baseDecay`: 1.0\n");
        md.append("- `abuseGain`: 0.3, `abuseIncrement`: 2.0, `abuseDecayRate`: 1.5\n");
        md.append("- `sustainedCostGain`: 0.35\n\n");

        md.append("| Step | Time (s) | Action / Phase | Cost | Decision | Burst | Sustained | Idle Credit | Abuse Score |\n");
        md.append("|:---:|:---:|:---|:---:|:---:|:---:|:---:|:---:|:---:|\n");

        ManualClock clock = new ManualClock(0.0);
        InMemoryStateStore store = new InMemoryStateStore();
        ConstantRateRefillStrategy refill = new ConstantRateRefillStrategy(10.0, 5.0, 30.0, 10.0);
        AdaptiveIdleCreditPolicy idle = new AdaptiveIdleCreditPolicy(5.0, 20.0, 1.0, 0.3, 2.0, 1.5);
        DREBLimiterV2 limiter = new DREBLimiterV2(store, clock, refill, idle, 30.0, 0.35);

        // Touch client at t=0
        limiter.peekState("client-example");
        int step = 0;

        // 1. Idle period: advance to t=10.0
        double currentTime = 10.0;
        clock.set(currentTime);

        // 2. Legitimate burst: 15 requests at 10ms intervals
        for (int i = 1; i <= 15; i++) {
            currentTime += 0.01;
            clock.set(currentTime);
            Decision d = limiter.allow("client-example", 1);
            ClientState s = limiter.peekState("client-example");
            step++;
            md.append(String.format(Locale.US,
                    "| %d | %.2f | Legitimate Burst #%d | 1 | **%s** | %.2f | %.2f | %.2f | %.3f |\n",
                    step, currentTime, i, d.name(), s.burstTokens, s.sustainedTokens, s.idleCredit, s.abuseScore));
        }

        // 3. 10 Repeated Burst Cycles: every 1.5s, fire 8 requests
        for (int cycle = 1; cycle <= 10; cycle++) {
            currentTime += 1.5;
            clock.set(currentTime);
            for (int r = 1; r <= 8; r++) {
                currentTime += 0.01;
                clock.set(currentTime);
                Decision d = limiter.allow("client-example", 1);
                ClientState s = limiter.peekState("client-example");
                step++;
                md.append(String.format(Locale.US,
                        "| %d | %.2f | Abuse Cycle %d (Req %d) | 1 | **%s** | %.2f | %.2f | %.2f | %.3f |\n",
                        step, currentTime, cycle, r, d.name(), s.burstTokens, s.sustainedTokens, s.idleCredit, s.abuseScore));
            }
        }

        Path docsDir = Paths.get("docs");
        if (!Files.exists(docsDir)) {
            Files.createDirectories(docsDir);
        }
        Path outputFile = docsDir.resolve("worked_example.md");
        Files.writeString(outputFile, md.toString());

        assertTrue(Files.exists(outputFile));
        assertTrue(Files.size(outputFile) > 100);
        System.out.println("Generated worked example at: " + outputFile.toAbsolutePath());
    }
}
